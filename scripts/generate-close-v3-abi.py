#!/usr/bin/env python3
"""Regenerate current zero-close/V5 SDK ABIs from a perps build. Historical exports are untouched."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--artifacts-dir", type=Path, default=root / "packages/perps/out")
args = parser.parse_args()
output = root / "packages/perps-aa-client/src/orderV3Abi.ts"
specs = {
    "orderRouterV3Abi": ("OrderRouter", {"commitOrder", "executeOrder", "expireOrder"}),
    "closePreviewV3Abi": ("CfdClosePreview", {"previewClose"}),
    "committedOrderV3Abi": ("CfdOrderPolicyEvaluator", {"assessCommittedOrder"}),
    "orderLifecycleV5Abi": ("OrderLifecycleBook", {"IntentRegistered", "OrderFinalized", "pendingIntent", "terminalOutcome", "orderTiming", "verifyReceipt", "lifecycleStatus", "currentExecutionConfigHash", "INTENT_TYPEHASH", "RECEIPT_TYPEHASH", "CONFIG_SCHEMA_HASH"}),
}
lines = ["// Generated by scripts/generate-close-v3-abi.py; retain historical ABI exports separately.\n"]
for export, (contract, names) in specs.items():
    artifact = json.loads((args.artifacts_dir / (contract + ".sol") / (contract + ".json")).read_text())
    abi = [item for item in artifact["abi"] if item.get("type") == "error" or item.get("name") in names]
    if contract == "CfdClosePreview":
        retired = {
            "CfdClosePreview__SponsoredDeploymentMismatch",
            "CfdClosePreview__SponsoredIntentInvalid",
            "CfdClosePreview__SponsoredAccountBusy",
            "CfdClosePreview__UncoveredCarry",
            "CfdClosePreview__SubsidyMismatch",
            "CfdEngine__InsufficientCloseOrderBountyBacking",
        }
        found = retired.intersection(item.get("name") for item in artifact["abi"])
        if found:
            raise ValueError(f"Stale sponsored-close preview errors in rebuilt ABI: {sorted(found)}")
        abi = [item for item in abi if item.get("name") != "previewClose" or item["inputs"][1]["type"] == "address"]
        preview = next(item for item in abi if item.get("name") == "previewClose")
        if any(part["name"] == "executionBountyUsdc" for part in preview["outputs"][0]["components"]):
            raise ValueError("Current ClosePreview still exposes the removed bounty output")
    lines.append(f"export const {export} = {json.dumps(abi, indent=2)} as const;\n")
lines.append("export const orderRouterV3TraderAbi = orderRouterV3Abi;\n")
output.write_text("\n".join(lines))
print(output.relative_to(root))

protection = json.loads(
    (args.artifacts_dir / "PositionProtectionBook.sol" / "PositionProtectionBook.json").read_text()
)
protection_output = root / "packages/perps-aa-client/src/protectionAbi.ts"
protection_output.write_text(
    "// Generated by scripts/generate-close-v3-abi.py; source-only, no deployment addresses.\n"
    f"export const positionProtectionBookAbi = {json.dumps(protection['abi'], indent=2)} as const;\n"
)
print(protection_output.relative_to(root))
